#!/usr/bin/env python3
"""sections.json -> docs/organon-data.js (the bundle the app and the tests read).

    python3 tools/extract.py && python3 tools/build-data.py
"""
import json

d = json.load(open("sections.json"))
meta = {k: d[k] for k in ("title", "edition", "translator", "source", "licence",
                          "total_in_book", "recovered", "missing", "scans",
                          "verification")}
sections = [{"n": s["n"], "text": s["text"], "from": s.get("from"),
             "corroboration": s.get("corroboration"), "diffWords": s.get("diff_words"),
             "notes": s.get("notes") or []} for s in d["sections"]]
out = (
    "/* The bundled text. Generated by tools/build-data.py from the archive.org OCR;\n"
    " * do not hand-edit. Public domain (Hahnemann d. 1843; Boericke translation 1922). */\n"
    "(function (root, factory) {\n"
    '  if (typeof module === "object" && module.exports) module.exports = factory();\n'
    "  else root.ORGANON = factory();\n"
    '})(typeof self !== "undefined" ? self : this, function () {\n'
    "  return " + json.dumps({"meta": meta, "sections": sections}, ensure_ascii=False) + ";\n});\n"
)
open("docs/organon-data.js", "w", encoding="utf-8").write(out)
print("docs/organon-data.js:", len(sections), "sections,", len(out), "bytes")
